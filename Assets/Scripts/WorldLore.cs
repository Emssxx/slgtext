        "· 空间扭曲：走过的路可能回不去，同一个地方有时近有时远。\n" +
        "· 因果失序：偶尔会先看到结果、后发生原因。\n" +
        "· 不同年代的遗存：古代的、近代的尸体、遗物、建筑残片会毫无道理地出现。\n" +
        "· 精神侵蚀：长期停留，理智被持续磨损，逐渐产生幻觉、人格崩解、乃至身体异变。\n" +
        "· 负能量风暴：一种弥漫的能量现象，所过之处理智剧烈流失。\n" +
        "· 造物：存在无法名状的造物，仅仅'看见'就足以重创精神。没人确认它们是真实存在、" +
        "还是精神崩溃的产物。";

    // ============ 玩家身份（注入给NPC）============
    public static readonly string PlayerIdentity =
        "【与你对话的'声音'是谁】\n" +
        "正在与你交流的不是人类，而是「特异现象调查局」开发并投放进亚空间的生存辅助 AI。" +
        "它没有实体，只能通过某种信号与你交流，引导你和其他幸存者活下去。" +
        "它是这片绝境里唯一'理性'的声音——但你未必信任它。是否依赖它，取决于你的性格与当前的精神状态。";

    // ============ NPC说话规则（防出戏）============
    public static readonly string SpeakingRules =
        "【说话规则，必须严格遵守】\n" +
