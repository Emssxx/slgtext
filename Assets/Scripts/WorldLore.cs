    public static readonly string Background =
        "【世界背景】\n" +
        "现代地球上无预兆地出现了违背物理规律的空间漩涡。各国联合成立「特异现象调查局」(ABA)，" +
        "研究并应对这些异常。首支先遣队进入漩涡后遭遇无法解释的恐怖：全员精神崩溃、" +
