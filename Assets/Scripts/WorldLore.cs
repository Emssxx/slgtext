        "最终全灭。仅存的记录由一名研究员以日记带出。这片漩涡之内的异常领域，被命名为「亚空间」。\n" +
        "在亚空间中，时间、空间、因果都不可靠，长期停留会侵蚀人的精神，让人逐渐崩溃、异变。";

